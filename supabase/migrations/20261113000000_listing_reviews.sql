create table public.listing_reviews (
  review_id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings(listing_id) on delete cascade,
  seller_id uuid not null references public."app-users"(user_id) on delete cascade,
  reviewer_id uuid not null references public."app-users"(user_id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  review_text text not null check (
    char_length(btrim(review_text)) between 1 and 1000
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (reviewer_id, listing_id)
);

create index listing_reviews_listing_id_idx
  on public.listing_reviews(listing_id, created_at desc);

create index listing_reviews_seller_id_idx
  on public.listing_reviews(seller_id, created_at desc);

create or replace function public.set_listing_review_seller()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  listing_seller_id uuid;
begin
  select listings.seller_id
  into listing_seller_id
  from public.listings
  where listings.listing_id = new.listing_id
    and listings.status = 'active';

  if listing_seller_id is null then
    raise exception 'The listing is not available for review.';
  end if;

  if new.reviewer_id = listing_seller_id then
    raise exception 'Sellers cannot review their own listings.';
  end if;

  if tg_op = 'UPDATE' and (
    new.listing_id <> old.listing_id
    or new.reviewer_id <> old.reviewer_id
  ) then
    raise exception 'The review listing and reviewer cannot be changed.';
  end if;

  new.seller_id := listing_seller_id;
  new.review_text := btrim(new.review_text);
  new.updated_at := now();
  return new;
end;
$$;

create trigger set_listing_review_seller_before_write
before insert or update on public.listing_reviews
for each row execute function public.set_listing_review_seller();

alter table public.listing_reviews enable row level security;

revoke all on public.listing_reviews from anon, authenticated;
grant select, insert, update, delete on public.listing_reviews to authenticated;
grant usage, select on sequence public.listing_reviews_review_id_seq to authenticated;

create policy "Authenticated users can read listing reviews"
on public.listing_reviews
for select
to authenticated
using (
  exists (
    select 1
    from public.listings
    where listings.listing_id = listing_reviews.listing_id
      and (
        listings.status = 'active'
        or listings.seller_id = (select auth.uid())
      )
  )
);

create policy "Users can review other sellers"
on public.listing_reviews
for insert
to authenticated
with check (
  reviewer_id = (select auth.uid())
  and seller_id <> (select auth.uid())
);

create policy "Users can update their own reviews"
on public.listing_reviews
for update
to authenticated
using (reviewer_id = (select auth.uid()))
with check (
  reviewer_id = (select auth.uid())
  and seller_id <> (select auth.uid())
);

create policy "Users can delete their own reviews"
on public.listing_reviews
for delete
to authenticated
using (reviewer_id = (select auth.uid()));
